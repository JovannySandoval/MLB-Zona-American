// ==========================================
// VARIABLES
// ==========================================

let preguntaActual = 0;

let puedeResponder = true;


// ==========================================
// ELEMENTOS
// ==========================================

const elementoPregunta =
    document.getElementById("pregunta");

const elementoOpciones =
    document.getElementById("opciones");

const elementoMensaje =
    document.getElementById("mensaje");

const botonSiguiente =
    document.getElementById("siguiente");

const numeroPregunta =
    document.getElementById("numeroPregunta");

const totalPreguntas =
    document.getElementById("totalPreguntas");

const progresoBarra =
    document.getElementById("progresoBarra");


// ==========================================
// INICIAR
// ==========================================

window.addEventListener("load", function () {

    totalPreguntas.textContent =
        preguntas.length;

    mostrarPregunta();

});


// ==========================================
// MOSTRAR PREGUNTA
// ==========================================

function mostrarPregunta() {

    puedeResponder = true;

    botonSiguiente.disabled = true;

    elementoMensaje.innerHTML = "";

    elementoOpciones.innerHTML = "";


    const pregunta =
        preguntas[preguntaActual];


    elementoPregunta.textContent =
        pregunta.pregunta;


    numeroPregunta.textContent =
        preguntaActual + 1;


    // ======================================
    // BARRA DE PROGRESO
    // ======================================

    const porcentaje =
        ((preguntaActual) /
        preguntas.length) * 100;


    progresoBarra.style.width =
        porcentaje + "%";


    // ======================================
    // CREAR OPCIONES
    // ======================================

    pregunta.opciones.forEach(
        function (opcion, indice) {

            const boton =
                document.createElement("button");


            boton.className =
                "opcion";


            boton.textContent =
                opcion;


            boton.onclick =
                function () {

                    comprobarRespuesta(
                        indice,
                        boton
                    );

                };


            elementoOpciones.appendChild(
                boton
            );

        }
    );

}


// ==========================================
// COMPROBAR RESPUESTA
// ==========================================

function comprobarRespuesta(
    indiceSeleccionado,
    botonSeleccionado
) {

    if (!puedeResponder) {
        return;
    }


    const pregunta =
        preguntas[preguntaActual];


    // ======================================
    // RESPUESTA CORRECTA
    // ======================================

    if (
        indiceSeleccionado ===
        pregunta.respuesta
    ) {

        puedeResponder = false;


        botonSeleccionado.classList.add(
            "correcta"
        );


        elementoMensaje.innerHTML =
            "✅ ¡Respuesta correcta!";


        elementoMensaje.style.color =
            "green";


        botonSiguiente.disabled = false;


        // Desactivar las demás opciones

        const botones =
            document.querySelectorAll(".opcion");


        botones.forEach(
            function (boton) {

                boton.disabled = true;

            }
        );

    }


    // ======================================
    // RESPUESTA INCORRECTA
    // ======================================

    else {

        botonSeleccionado.classList.add(
            "incorrecta"
        );


        elementoMensaje.innerHTML =
            "❌ Respuesta incorrecta. Inténtalo nuevamente.";


        elementoMensaje.style.color =
            "red";


        // Solamente deshabilitamos
        // momentáneamente el botón equivocado

        botonSeleccionado.disabled = true;


        setTimeout(function () {

            botonSeleccionado.classList.remove(
                "incorrecta"
            );

        }, 500);

    }

}


// ==========================================
// SIGUIENTE PREGUNTA
// ==========================================

function siguientePregunta() {

    if (preguntaActual >= preguntas.length - 1) {

        terminarTrivia();

        return;

    }


    preguntaActual++;


    mostrarPregunta();

}


// ==========================================
// TERMINAR TRIVIA
// ==========================================

function terminarTrivia() {

    elementoPregunta.style.display =
        "none";

    elementoOpciones.style.display =
        "none";

    botonSiguiente.style.display =
        "none";

    elementoMensaje.style.display =
        "none";

    document.querySelector(".progreso").style.display =
        "none";

    document.querySelector(".barra").style.display =
        "none";


    document.getElementById(
        "resultadoFinal"
    ).style.display = "block";

}


// ==========================================
// REINICIAR
// ==========================================

function reiniciarTrivia() {

    preguntaActual = 0;

    elementoPregunta.style.display =
        "block";

    elementoOpciones.style.display =
        "flex";

    botonSiguiente.style.display =
        "inline-block";

    elementoMensaje.style.display =
        "block";

    document.querySelector(".progreso").style.display =
        "block";

    document.querySelector(".barra").style.display =
        "block";


    document.getElementById(
        "resultadoFinal"
    ).style.display = "none";


    mostrarPregunta();

}